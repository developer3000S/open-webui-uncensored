<script lang="ts">
	import { getContext, createEventDispatcher } from 'svelte';

	import { toast } from 'svelte-sonner';

	import Spinner from '$lib/components/common/Spinner.svelte';

	import {
		getCoderCIStatus,
		suggestCoderTests,
		type CoderCIStatus
	} from '$lib/apis/coder';

	const i18n = getContext('i18n');
	const dispatch = createEventDispatcher();

	export let token: string;
	export let owner = '';
	export let repo = '';
	export let branch = '';

	let ciStatus: CoderCIStatus | null = null;
	let loadingCI = false;
	let generatingTests = false;

	const stateColor = (state: string): string => {
		switch (state) {
			case 'success':
				return 'bg-green-100 text-green-700 dark:bg-green-950/50 dark:text-green-400';
			case 'failure':
			case 'error':
				return 'bg-red-100 text-red-700 dark:bg-red-950/50 dark:text-red-400';
			case 'pending':
			case 'in_progress':
			case 'queued':
				return 'bg-yellow-100 text-yellow-700 dark:bg-yellow-950/50 dark:text-yellow-400';
			default:
				return 'bg-gray-100 text-gray-600 dark:bg-gray-800 dark:text-gray-400';
		}
	};

	const refreshCI = async () => {
		if (!owner || !repo) return;
		loadingCI = true;
		try {
			ciStatus = await getCoderCIStatus(token, owner, repo, branch);
		} catch (e: any) {
			toast.error(e?.detail?.message ?? e?.message ?? 'Failed to load CI status');
			ciStatus = null;
		} finally {
			loadingCI = false;
		}
	};

	const generateTests = async () => {
		if (!owner || !repo) {
			toast.error($i18n.t('Select a repository first'));
			return;
		}
		generatingTests = true;
		try {
			const res = await suggestCoderTests(token, {
				owner,
				repo,
				title: `Auto-generated test skeleton for ${branch || 'default branch'}`
			});
			toast.success(
				res.generated_by_model
					? $i18n.t('Test skeleton generated by model and added to the issue backlog')
					: $i18n.t('Test skeleton created as a GitHub issue')
			);
			dispatch('tests', res);
		} catch (e: any) {
			toast.error(e?.detail?.message ?? e?.message ?? 'Failed to generate tests');
		} finally {
			generatingTests = false;
		}
	};
</script>

<div class="flex items-center gap-1.5 shrink-0">
	<button
		type="button"
		class="text-xs px-2 py-1 rounded-lg bg-gray-100 dark:bg-gray-800 hover:bg-gray-200 dark:hover:bg-gray-700 disabled:opacity-40 flex items-center gap-1"
		disabled={loadingCI || !owner || !repo}
		title={$i18n.t('Refresh CI status')}
		on:click={refreshCI}>
		{#if loadingCI}
			<Spinner className="size-3" />
		{:else}
			<svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.5" stroke="currentColor" class="size-3.5">
				<path
					stroke-linecap="round"
					stroke-linejoin="round"
					d="M16.023 9.348h4.992v-.003a2.999 2.999 0 0 0-2.108-2.813 3 3 0 1 0-5.823 0A3 3 0 0 0 11 9.345Zm-8 0H4.015v-.003a2.999 2.999 0 0 1 2.108-2.813 3 3 0 1 1 5.823 0A3 3 0 0 1 16 9.345Z"
				/>
			</svg>
		{/if}
		{$i18n.t('CI')}
		{#if ciStatus}
			<span class="px-1.5 py-0.5 rounded text-[10px] {stateColor(ciStatus.state)}">{ciStatus.state}</span>
		{/if}
	</button>

	{#if ciStatus && ciStatus.checks.length > 0}
		<div class="hidden xl:flex items-center gap-1 max-w-[260px] overflow-x-auto scrollbar-thin">
			{#each ciStatus.checks.slice(0, 8) as c (c.name)}
				<a
					href={c.url ?? '#'}
					target="_blank"
					rel="noopener noreferrer"
					class="text-[10px] px-1.5 py-0.5 rounded whitespace-nowrap {stateColor(c.conclusion ?? c.status)}"
					title="{c.name}: {c.status} {c.conclusion ?? ''}">{c.name}</a
				>
			{/each}
		</div>
	{/if}

	<button
		type="button"
		class="text-xs px-2 py-1 rounded-lg bg-gray-100 dark:bg-gray-800 hover:bg-gray-200 dark:hover:bg-gray-700 disabled:opacity-40 flex items-center gap-1"
		disabled={generatingTests || !owner || !repo}
		title={$i18n.t('Generate test skeleton (creates a GitHub issue)')}
		on:click={generateTests}>
		{#if generatingTests}
			<Spinner className="size-3" />
		{:else}
			<svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.5" stroke="currentColor" class="size-3.5">
				<path
					stroke-linecap="round"
					stroke-linejoin="round"
					d="M9.75 3.104v5.714a2.25 2.25 0 0 1-.659 1.591L5 14.5M9.75 3.104c-.251.023-.501.05-.75.082m.75-.082a24.3 24.3 0 0 1 4.5 0m0 0v5.714c0 .597.237 1.17.659 1.591L19.8 15.3M14.25 3.104c.251.023.501.05.75.082M19.8 15.3l-1.57.393A9.06 9.06 0 0 1 12 18a9.06 9.06 0 0 1-6.23-.307L4.2 15.3m15.6 0a2.4 2.4 0 1 0-4.8 0 2.4 2.4 0 0 0 4.8 0Zm-15.6 0a2.4 2.4 0 1 0 4.8 0 2.4 2.4 0 0 0-4.8 0Z"
				/>
			</svg>
		{/if}
		{$i18n.t('Tests')}
	</button>
</div>
